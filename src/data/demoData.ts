let demoItemCounter = 0;

function makeDemoItem(
  partial: Omit<WardrobeItem, 'userId' | 'createdAt' | 'updatedAt' | 'imageUrl'> & {
    imageUrl?: string;
  }
): WardrobeItem {
  const offsetDays = demoItemCounter++;
  const createdDate = new Date(Date.UTC(2026, 8, 30 - offsetDays, 10, 0, 0)).toISOString();
  const imageUrl =
    partial.imageUrl ||
    getGarmentStudioSvgDataUrl({
      category: partial.category,
      subcategory: partial.subcategory,
      primaryColor: partial.primaryColor,
      secondaryColor: partial.secondaryColor,
      pattern: partial.pattern,
      name: partial.name,
    });

  return {
    ...partial,
    userId: 'demo_user',
    imageUrl,
    createdAt: createdDate,
    updatedAt: createdDate,
  };
}

